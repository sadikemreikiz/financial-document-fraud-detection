"""The generated report of the BoW + LR baseline, rendered from its run records (ADR-0011)."""

from typing import Any

from docfraud.evaluation.runs import RunRecord
from docfraud.markdown import Table, render_table

METRICS = (
    ("precision", "Precision"),
    ("recall", "Recall"),
    ("f1", "F1"),
    ("average_precision", "Average precision"),
    ("roc_auc", "ROC-AUC"),
    ("mcc", "MCC"),
    ("recall_at_10pct_review", "Recall at 10 % review"),
    ("recall_at_20pct_review", "Recall at 20 % review"),
)


def _pct(estimate: dict[str, float]) -> str:
    return (
        f"{estimate['value'] * 100:.2f} [{estimate['low'] * 100:.1f}, {estimate['high'] * 100:.1f}]"
    )


def _counts(counts: dict[str, int]) -> str:
    return f"{counts['tp']} / {counts['fp']} / {counts['fn']} / {counts['tn']}"


def _run_line(record: RunRecord) -> str:
    code = record.code.commit[:7] if record.code.commit else "unknown"
    dirty = ", uncommitted changes" if record.code.dirty else ""
    return f"run `{record.run_id}` (commit {code}{dirty})"


def render_report(cv: RunRecord, test: RunRecord | None) -> str:
    """Cross-validated development result and, once it exists, the single test evaluation."""
    r: dict[str, Any] = cv.results
    parts = [
        "# BoW + LR baseline\n\n"
        "Generated by `docfraud baseline report` from run records; do not edit by hand.\n\n"
        "The published bag-of-words + logistic-regression baseline (Martínez Tornés et al., "
        "ICDAR 2023, Table 4), re-implemented with the configuration fixed in "
        "[ADR-0011](../../docs/decisions/0011-baseline-reproduction.md): scikit-learn "
        "`CountVectorizer` and `LogisticRegression` with default settings, trained on the "
        "normalised transcripts of the training split, forged when the probability exceeds "
        "0.5.\n\n"
    ]
    if test is None:
        parts.append(
            "### Reproduction on the test split\n\nNot run yet. The test split is unlocked once, "
            "under the evaluation protocol's exception 1.\n\n"
        )
    else:
        t: dict[str, Any] = test.results
        published = t["published"]
        rows = [
            (label, f"{published[key] * 100:.2f}", _pct(t["metrics"][key]))
            for key, label in METRICS[:3]
        ]
        rows.append(
            (
                "Forged found / authentic flagged / forged missed",
                f"{published['tp']} / {published['fp']} / {published['fn']}",
                f"{t['counts']['tp']} / {t['counts']['fp']} / {t['counts']['fn']}",
            )
        )
        verdict = "passed" if t["reproduced"] else "failed"
        parts.append(
            render_table(
                Table(
                    "Reproduction on the test split",
                    ("Metric", "Published", "Ours [95 % interval]"),
                    rows,
                    note=f"{t['n_documents']} test receipts, {t['n_forged']} forged; "
                    f"{_run_line(test)}, test split unlocked once: "
                    f'"{"; ".join(test.test_unlocks)}". Criterion (ADR-0011): the published F1 '
                    f"lies inside our 95 % interval. **Reproduction {verdict}.** The criterion is "
                    "weak by design: the published F1 rests on four forged receipts, so it rules "
                    "out gross errors such as inverted labels, not small differences.",
                )
            )
            + "\n"
        )
    cv_rows = [(label, _pct(r["metrics"][key])) for key, label in METRICS]
    cv_rows.append(
        (
            "Counts: forged found / authentic flagged / forged missed / authentic passed",
            _counts(r["counts"]),
        )
    )
    parts.append(
        render_table(
            Table(
                "Cross-validation on the training split (development reference)",
                ("Metric", "Value [95 % interval]"),
                cv_rows,
                note=f"Out-of-fold predictions of the {r['n_documents']} training receipts "
                f"({r['n_forged']} forged), 5 stored folds; percentages, stratified bootstrap "
                f"over receipts. Iteration limit per fold: {r['max_iter']}. {_run_line(cv)}.",
            )
        )
    )
    return "".join(parts)
