"""Where the rules' shift between the splits comes from (ADR-0029, section 7 (d)).

Writes reports/fusion/input-shift-rules.md. The comparison of the inputs of both splits
(reports/fusion/input-shift.md) found the rules' score shifted on both text sources. A
training receipt's score comes from the scorer of its fold, one of five fitted on the other
folds, and a validation receipt's from one scorer fitted on every training receipt. This
diagnostic, made after that comparison and not pre-registered, separates the two: it applies
the one scorer to the training receipts as well, and compares again. Nothing in the pipeline
changes with its result.

The rule outcomes of the training receipts are rebuilt from the frozen LLM reader's stored
answers (no request is sent), and the one scorer is refitted on them and checked against the
weights the validation-inputs record holds. Training labels enter only that fit, as in the
pipeline; no label of a validation receipt is read.

Usage: ``uv run python experiments/input_shift_rules.py`` (needs the dataset, the OCR cache,
artifacts/llm and both inputs tables under artifacts/fusion)
"""

from pathlib import Path

import numpy as np

from docfraud.cli.common import OCR_CACHE, REPORTED_RUNS, TRACKS, cached_ocr, findit_documents
from docfraud.cli.fusion import TRAINING_INPUTS, VALIDATION_INPUTS, _frozen_reader, _reading
from docfraud.data.models import Label, Split
from docfraud.data.splits import select
from docfraud.detectors.scoring import features
from docfraud.evaluation.runs import JsonRunStore
from docfraud.fusion.development_report import TRACK_NAMES
from docfraud.fusion.shift import ks_distance, permutation_test
from docfraud.fusion.training_inputs import load_table
from docfraud.fusion.validation_inputs import RUN_NAME, rules_scorers
from docfraud.markdown import Cell, Table, render_table

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "reports" / "fusion" / "input-shift-rules.md"


def main() -> None:
    """Write the report."""
    train = sorted(select(findit_documents(ROOT / "data"), Split.TRAIN), key=lambda d: d.doc_id)
    ocr, reader = cached_ocr(ROOT / OCR_CACHE), _frozen_reader()
    outcomes = {t.value: [_reading(d, ocr, reader, t)[0] for d in train] for t in TRACKS}
    scorers = rules_scorers(outcomes, [d.label is Label.FORGED for d in train])
    record = JsonRunStore(ROOT / REPORTED_RUNS).records(RUN_NAME)[-1]
    training, validation = load_table(ROOT / TRAINING_INPUTS), load_table(ROOT / VALIDATION_INPUTS)
    rows: list[list[Cell]] = []
    for track, name in TRACK_NAMES.items():
        if scorers[track].weights() != record.results["rules_scorers"][track]:
            msg = f"the refitted scorer of {track} is not the one {record.run_id} used"
            raise ValueError(msg)
        folds = np.array([r.inputs["rules"] for r in training.rows(track, 0)])
        one = scorers[track].scores(features(outcomes[track]))
        checked = np.array([r.inputs["rules"] for r in validation.rows(track, 0)])
        for scores, how in (
            (folds, "training, by the five fold scorers"),
            (one, "training, by the one scorer"),
        ):
            test = permutation_test(scores, checked)
            rows.append(
                [
                    name,
                    how,
                    len(np.unique(scores)),
                    float(scores.mean()),
                    test.distance,
                    test.critical,
                    f"{test.p_value:.4f}",
                ]
            )
        rows.append(
            [
                name,
                "validation, by the one scorer",
                len(np.unique(checked)),
                float(checked.mean()),
                None,
                None,
                None,
            ]
        )
        rows.append(
            [
                name,
                "training: the five fold scorers against the one",
                None,
                None,
                ks_distance(folds, one),
                None,
                None,
            ]
        )
    table = Table(
        "The rules' score of the training receipts, scored two ways, against validation",
        (
            "Text source",
            "Receipts, scored",
            "Distinct values",
            "Mean",
            "KS distance D to validation",
            "D for p < 0.05",
            "p",
        ),
        rows,
        note="562 training and 190 validation receipts; permutation test with 10,000 shuffles, "
        "seed 0, as in the comparison of the inputs. The last row of each text source compares "
        "the two ways of scoring the same training receipts with each other.",
    )
    header = (
        "# Where the rules' shift between the splits comes from\n\n"
        "> Generated by `experiments/input_shift_rules.py`. Do not edit by hand.\n\n"
        "A diagnostic of the [comparison of the inputs](input-shift.md), made after it and not "
        "pre-registered; nothing in the pipeline changes with its result. The rules' score of a "
        "training receipt comes from the scorer of its fold, one of five, and that of a "
        "validation receipt from one scorer fitted on every training receipt "
        "([ADR-0029](../../docs/decisions/0029-fusion-preregistration.md), section 2). Applying "
        "the one scorer to the training receipts too shows whether the shift lies in the "
        "scoring or in the receipts. No label of a validation receipt is read.\n\n"
    )
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(header + render_table(table), encoding="utf-8")
    print(f"written: {OUTPUT.relative_to(ROOT)}")  # noqa: T201


if __name__ == "__main__":
    main()
