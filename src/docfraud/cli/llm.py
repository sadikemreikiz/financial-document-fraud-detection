GOLD_B = GOLD_B_MANIFEST
MAX_ROUNDS = 10

Instruction = Annotated[Path, typer.Option(help="The fixed instructions the model reads.")]
Store = Annotated[Path, typer.Option(help="Where responses are kept.")]
